import test from 'node:test';
import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { once } from 'node:events';
import { openStore } from '../src/store.mjs';
import { handleAdmin } from '../src/admin.mjs';
test('admin requires bearer auth, rejects cross-site actions and persists explicit mode changes', async t => {
  const store = openStore(':memory:');
  store.ingest({ id: 'p:1', phoneNumberId: 'p', contactId: '5511000000000', timestamp: Date.now(), kind: 'text', text: 'Preciso de ajuda' });
  store.saveHandoff('5511000000000', '<img src=x onerror=alert(1)>');
  const token = 'x'.repeat(32);
  const server = createServer((req, res) => handleAdmin(req, res, { store, config: { adminToken: token, publicOrigin: 'https://bot.example.com' } }));
  server.listen(0, '127.0.0.1'); await once(server, 'listening');
  const base = `http://127.0.0.1:${server.address().port}`;
  t.after(async () => { server.closeAllConnections(); await new Promise(r => server.close(r)); store.close(); });
  const headers = { Authorization: `Bearer ${token}` };
  assert.equal((await fetch(base + '/admin/conversations')).status, 401);
  assert.equal((await fetch(base + '/admin/conversations', { headers: { Authorization: 'Bearer wrong' } })).status, 401);
  const list = await fetch(base + '/admin/conversations', { headers });
  assert.equal(list.headers.get('cache-control'), 'no-store');
  assert.equal((await list.json()).conversations.length, 1);
  const url = base + '/admin/conversations/5511000000000/mode';
  const post = (mode, extra = {}) => fetch(url, { method: 'POST', headers: { ...headers, 'Content-Type': 'application/json', ...extra }, body: JSON.stringify({ mode }) });
  assert.equal((await post('auto', { Origin: 'https://evil.example' })).status, 403);
  assert.equal((await post('invalid')).status, 400);
  assert.equal((await post('human')).status, 200);
  assert.equal(store.getConversation('5511000000000').mode, 'human');
  const revision = store.getConversation('5511000000000').revision;
  store.ingest({ id: 'p:2', phoneNumberId: 'p', contactId: '5511000000000', timestamp: Date.now(), kind: 'text', text: 'Mais detalhes' });
  assert.equal(store.getConversation('5511000000000').mode, 'human');
  assert.equal((await post('auto')).status, 200);
  assert.ok(store.getConversation('5511000000000').revision > revision);
  const shell = await fetch(base + '/admin');
  assert.equal(shell.status, 200);
  assert.equal(shell.headers.get('content-security-policy').includes("frame-ancestors 'none'"), true);
  assert.equal((await shell.text()).includes(token), false);
  assert.equal((await fetch(base + '/admin/../../package.json', { headers })).status, 404);
});
